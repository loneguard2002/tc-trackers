"""Standalone report rendering: a self-contained HTML document, converted to PDF or PNG with headless Chromium."""

from __future__ import annotations

import os
from pathlib import Path

from flask import current_app, render_template
from playwright.sync_api import sync_playwright

from .build import Report

A4_PORTRAIT_WIDTH = 794  # CSS pixels at 96 dpi
RENDER_TIMEOUT_MS = 20_000


def render_print_html(report: Report) -> str:
    """The report as one self-contained document: CSS inlined, charts embedded as data URIs, no scripts."""
    css = (Path(current_app.static_folder) / "tracker.css").read_text(encoding="utf-8")
    return render_template("report/print.html", report=report, css=css, chart_mime="image/svg+xml")


def _launch_args() -> list[str]:
    """``--no-sandbox`` as root, or when TRACKER_CHROMIUM_NO_SANDBOX=1 (containers often lack the user namespaces).

    Acceptable because the HTML is generated by this application: it carries no external content and no scripts.
    """
    as_root = hasattr(os, "geteuid") and os.geteuid() == 0
    return ["--no-sandbox"] if as_root or os.environ.get("TRACKER_CHROMIUM_NO_SANDBOX") == "1" else []


def _open(playwright, width: int, height: int, html: str):
    browser = playwright.chromium.launch(args=_launch_args(), timeout=RENDER_TIMEOUT_MS)
    try:
        page = browser.new_page(viewport={"width": width, "height": height})
        page.set_default_timeout(RENDER_TIMEOUT_MS)
        page.set_content(html, wait_until="load", timeout=RENDER_TIMEOUT_MS)
    except BaseException:
        browser.close()
        raise
    return browser, page


def html_to_pdf(html: str) -> bytes:
    """Render ``html`` to an A4 PDF."""
    with sync_playwright() as playwright:
        browser, page = _open(playwright, A4_PORTRAIT_WIDTH, 1123, html)
        try:
            return page.pdf(format="A4", print_background=True)
        finally:
            browser.close()


def html_to_png(html: str, width: int = 1100) -> bytes:
    """Render ``html`` to a full-page PNG ``width`` CSS pixels wide."""
    with sync_playwright() as playwright:
        browser, page = _open(playwright, width, 800, html)
        try:
            return page.screenshot(full_page=True, type="png")
        finally:
            browser.close()
